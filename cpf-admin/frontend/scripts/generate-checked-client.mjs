import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const specPath = path.resolve(process.env.CPF_OPENAPI_FILE || "openapi/cpf-openapi.json");
const spec = JSON.parse(fs.readFileSync(specPath, "utf8"));
const sourceSha = process.env.CPF_SOURCE_SHA || spec["x-cpf-source-sha"];
if (!/^[0-9a-f]{40}$/.test(sourceSha || "")) throw new Error("CPF_SOURCE_SHA 또는 x-cpf-source-sha가 필요합니다.");
const operations = [];
for (const [url, methods] of Object.entries(spec.paths || {})) {
  for (const [method, operation] of Object.entries(methods || {})) {
    if (!operation || typeof operation !== "object" || !operation.operationId) continue;
    operations.push({ url, method: method.toUpperCase(), operationId: operation.operationId });
  }
}
operations.sort((a, b) => a.operationId.localeCompare(b.operationId));
const lines = [
  "/* eslint-disable */",
  "// Generated by scripts/generate-checked-client.mjs. Do not edit manually.",
  'import { cpfOrvalRequest } from "../shared/orval-mutator";',
  "",
  "export interface CpfGeneratedRequestOptions { data?: unknown; signal?: AbortSignal; headers?: HeadersInit; }",
  ""
];
for (const operation of operations) {
  lines.push(`export async function ${operation.operationId}<T = unknown>(options: CpfGeneratedRequestOptions = {}): Promise<T> {`);
  lines.push("  return cpfOrvalRequest<T>({");
  lines.push(`    url: ${JSON.stringify(operation.url)},`);
  lines.push(`    method: ${JSON.stringify(operation.method)},`);
  lines.push("    data: options.data,");
  lines.push("    signal: options.signal,");
  lines.push("    headers: options.headers");
  lines.push("  });");
  lines.push("}", "");
}
const generatedDir = path.join(root, "src/generated");
fs.mkdirSync(generatedDir, { recursive: true });
const target = path.join(generatedDir, "cpf-api.ts");
const content = lines.join("\n") + "\n";
fs.writeFileSync(target, content, "utf8");
const sha256 = value => crypto.createHash("sha256").update(value).digest("hex");
const marker = {
  schemaVersion: 2,
  sourceSha,
  openApiPath: path.relative(root, specPath).replaceAll("\\", "/"),
  openApiSha256: sha256(fs.readFileSync(specPath)),
  generatedFiles: [{ path: "src/generated/cpf-api.ts", sha256: sha256(content) }],
  generator: "scripts/generate-checked-client.mjs",
  generatorSha256: sha256(fs.readFileSync(new URL(import.meta.url)))
};
fs.writeFileSync(path.join(generatedDir, ".cpf-openapi-source.json"), JSON.stringify(marker, null, 2) + "\n", "utf8");
fs.writeFileSync(path.join(generatedDir, "source-sha.json"), JSON.stringify({ sourceSha }, null, 2) + "\n", "utf8");
