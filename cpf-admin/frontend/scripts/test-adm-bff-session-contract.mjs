import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "../../..");
const read = p => fs.readFileSync(path.join(root,p),"utf8");
const build = read("cpf-admin/build.gradle");
const app = read("cpf-admin/src/main/java/com/cpf/admin/AdmApplication.java");
const auth = read("cpf-admin/src/main/java/com/cpf/admin/opr/controller/AdmAuthController.java");
const dto = read("cpf-admin/src/main/java/com/cpf/admin/opr/dto/AdmLoginResponse.java");
const yml = read("cpf-admin/src/main/resources/application.yml");
const api = read("cpf-admin/frontend/src/shared/cpfApi.ts");
const mutator = read("cpf-admin/frontend/src/shared/orval-mutator.ts");
const advice = read("cpf-starters/security/session/jdbc/src/main/java/com/cpf/security/session/jdbc/CpfBffCredentialResponseAdvice.java");
const bridge = read("cpf-starters/security/session/jdbc/src/main/java/com/cpf/security/session/jdbc/CpfBffSessionBridgeFilter.java");
assert.match(build, /:starters:security:session:jdbc/);
assert.match(app, /paramName = "CPFSESSION"/);
assert.match(yml, /store-type: jdbc/);
assert.match(yml, /initialize-schema: never/);
assert.match(yml, /cookie-name: \$\{CPF_ADM_SESSION_COOKIE:CPFSESSION\}/);
assert.match(yml, /same-site: \$\{CPF_ADM_SESSION_SAME_SITE:Strict\}/);
assert.match(yml, /secure: \$\{CPF_ADM_SESSION_COOKIE_SECURE:true\}/);
assert.match(dto, /@Schema\(hidden = true\) String accessToken/);
assert.doesNotMatch(auth, /Bearer 토큰 세션을 발급/);
assert.match(api, /Browser Bearer Token을 허용하지 않습니다/);
assert.match(mutator, /Browser Bearer Token 금지/);
assert.match(advice, /CREDENTIAL_KEYS = Set\.of\("accessToken", "refreshToken"\)/);
assert.match(advice, /httpRequest\.changeSessionId\(\)/);
assert.match(bridge, /Browser Authorization header is prohibited/);
assert.match(bridge, /"Authorization"\.equalsIgnoreCase\(name\) \? "Bearer " \+ token/);
console.log("[CPF][ADM][PASS] HttpOnly JDBC BFF session, CSRF, fixation rotation, encrypted internal credential bridge");
