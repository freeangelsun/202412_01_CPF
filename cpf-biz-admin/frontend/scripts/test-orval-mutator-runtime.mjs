import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "cpf-bza-mutator-runtime-"));
const source = path.join(root, "src/shared/orval-mutator.ts");
const compile = spawnSync(process.platform === "win32" ? "npx.cmd" : "npx", ["--no-install","tsc",source,"--target","ES2022","--module","ES2022","--moduleResolution","Bundler","--strict","--lib","ES2022,DOM,DOM.Iterable","--skipLibCheck","--outDir",temp], {cwd:root,encoding:"utf8"});
if(compile.status!==0)throw new Error(`mutator compile failed:\n${compile.stdout}\n${compile.stderr}`);
const js=path.join(temp,"orval-mutator.js");
const mjs=path.join(temp,"orval-mutator.mjs");
fs.renameSync(js,mjs);
globalThis.window={location:{origin:"https://cpf.example"}};
globalThis.document={cookie:"XSRF-TOKEN=csrf"};
let responses=[]; const calls=[];
globalThis.fetch=async (url,options)=>{calls.push({url:String(url),options});const next=responses.shift();if(!next)throw new Error("no mock response");return next;};
const response=(status,payload)=>new Response(JSON.stringify(payload),{status,headers:{"Content-Type":"application/json"}});
const api=await import(pathToFileURL(mjs).href);
responses=[response(200,{ok:true})];
const result=await api.cpfOrvalRequest({url:"/api/bza/example",method:"GET"});
assert.deepEqual(result.data,{ok:true});assert.equal(result.status,200);assert.ok(result.headers instanceof Headers);
assert.equal(calls.at(-1).options.credentials,"include");assert.equal(calls.at(-1).options.cache,"no-store");
await assert.rejects(()=>api.cpfOrvalRequest({url:"/api/bza/example",method:"GET",data:{bad:true}}),/GET request body is forbidden/);
await assert.rejects(()=>api.cpfOrvalRequest({url:"/api/bza/example",method:"POST",data:{operatorId:"spoof"}}),/Browser actor field is forbidden/);
await assert.rejects(()=>api.cpfOrvalRequest({url:"https://evil.example/api/bza/example",method:"GET"}),/same-origin/);
let refreshCount=0;let clearCount=0;let epoch=3;
api.configureCpfBffSessionRecovery({epoch:()=>epoch,refresh:async expected=>{assert.equal(expected,3);refreshCount++;},clear:expected=>{assert.equal(expected,3);clearCount++;}});
responses=[response(401,{message:"expired"}),response(200,{recovered:true})];
const recovered=await api.cpfOrvalRequest({url:"/api/bza/example",method:"GET"});
assert.deepEqual(recovered.data,{recovered:true});assert.equal(refreshCount,1);assert.equal(clearCount,0);assert.equal(calls.length,3);
responses=[response(401,{message:"expired"}),response(401,{message:"still expired"})];
await assert.rejects(()=>api.cpfOrvalRequest({url:"/api/bza/example",method:"GET"}),error=>error instanceof api.CpfOrvalError&&error.status===401);
assert.equal(refreshCount,2);assert.equal(clearCount,1);
console.log("[CPF][BZA][FRONTEND][PASS] Orval mutator envelope, same-origin, actor boundary and single-flight session recovery");
